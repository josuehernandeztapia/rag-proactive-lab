#!/usr/bin/env python3
"""Construct HASE training dataset merging consumption features with default labels.

Usage:
    python agents/hase/scripts/build_training_dataset.py --labels data/processed/hase/dummy_labels.csv
    python agents/hase/scripts/build_training_dataset.py \
        --features data/processed/hase/consumos_features_daily.csv.gz \
        --labels data/processed/hase/dummy_labels.csv \
        --output data/processed/hase/hase_training_dataset.csv

Une rolling features con etiquetas y genera el dataset listo para entrenamiento."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Iterable

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from config.loader import PROJECT_ROOT, get_config, get_path
from config.metadata import write_metadata

BASE_REQUIRED_COLS = [
    "plaza_limpia",
    "placa",
    "fecha_dia",
    "litros_diarios",
    "litros_7d",
    "litros_14d",
    "litros_30d",
    "tickets_diarios",
    "tickets_7d",
    "tickets_14d",
    "tickets_30d",
    "recaudo_diario",
    "recaudo_7d",
    "recaudo_14d",
    "recaudo_30d",
    "precio_promedio",
    "recencia_dias",
    "credito_diario",
    "credito_7d",
    "credito_14d",
    "credito_30d",
    "coverage_ratio_7d",
    "coverage_ratio_14d",
    "coverage_ratio_30d",
    "downtime_days_14d",
    "downtime_days_30d",
]

ROLLING_OPTIONAL_COLS = [
    "downtime_hours",
    "downtime_hours_7d",
    "downtime_hours_14d",
    "downtime_hours_30d",
    "downtime_days_7d",
    "protections_applied_last_12m",
    "days_since_last_protection",
]

TELEMETRY_BASE_COLS = [
    "trip_count",
    "seatbelt_off_events",
    "stop_hours",
    "speed_range1_hours",
    "speed_range2_hours",
    "speed_range3_hours",
    "speed_range1_km",
    "speed_range2_km",
    "speed_range3_km",
    "driving_hours",
    "engine_hours",
    "idling_hours",
    "distance_km",
    "after_hours_distance_km",
    "after_hours_driving_hours",
    "after_hours_stop_hours",
    "work_distance_km",
    "work_driving_hours",
    "work_stop_hours",
]

TELEMETRY_MEAN_COLS = ["average_speed_kph"]
TELEMETRY_MAX_COLS = ["max_speed_kph"]
TELEMETRY_WINDOWS = (7, 14, 30)

TELEMETRY_RATIO_COLS = [
    "seatbelt_off_rate_30d",
    "high_speed_hours_30d",
    "high_speed_ratio_30d",
    "idle_hours_ratio_30d",
]


def _build_default_feature_cols() -> list[str]:
    cols: list[str] = list(BASE_REQUIRED_COLS)
    cols.extend(ROLLING_OPTIONAL_COLS)
    cols.extend(TELEMETRY_BASE_COLS)
    for window in TELEMETRY_WINDOWS:
        suffix = f"_{window}d"
        cols.extend(f"{col}{suffix}" for col in TELEMETRY_BASE_COLS)
        cols.extend(f"{col}{suffix}" for col in TELEMETRY_MEAN_COLS)
        cols.extend(f"{col}{suffix}_max" for col in TELEMETRY_MAX_COLS)
    cols.extend(TELEMETRY_RATIO_COLS)
    # Remove duplicates while preserving order
    seen: set[str] = set()
    ordered: list[str] = []
    for col in cols:
        if col in seen:
            continue
        seen.add(col)
        ordered.append(col)
    return ordered


DEFAULT_FEATURE_COLS = _build_default_feature_cols()

DEFAULT_FEATURES_PATH = get_path('data', 'processed', 'hase', 'features_daily')
DEFAULT_LABELS_PATH = get_path('data', 'processed', 'hase', 'dummy_labels')
DEFAULT_OUTPUT_PATH = get_path('data', 'processed', 'hase', 'training_dataset')
DEFAULT_OBSERVATION_WINDOW = int(get_config('hase', 'observation_window_days', default=30))


def _rel(path: Path) -> str:
    try:
        return str(path.relative_to(PROJECT_ROOT))
    except ValueError:
        return str(path)


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build HASE training dataset")
    parser.add_argument(
        "--features",
        type=Path,
        default=DEFAULT_FEATURES_PATH,
        help="Daily feature table generated by build_consumo_features.py",
    )
    parser.add_argument(
        "--labels",
        type=Path,
        default=DEFAULT_LABELS_PATH,
        help="CSV with at least columns {placa, default_flag} and optional label_date",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Path to write merged training dataset",
    )
    parser.add_argument(
        "--observation-window",
        type=int,
        default=DEFAULT_OBSERVATION_WINDOW,
        help="Number of days before label_date to enforce observation window",
    )
    return parser.parse_args(argv)


def load_features(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Features file not found: {path}")
    df = pd.read_csv(path)
    if "last_protection_at" in df.columns and "days_since_last_protection" not in df.columns:
        df["last_protection_at"] = pd.to_datetime(
            df["last_protection_at"], errors="coerce", utc=True
        ).dt.tz_localize(None)
        reference_date = pd.Timestamp.utcnow().normalize()
        df["days_since_last_protection"] = df["last_protection_at"].apply(
            lambda value: (reference_date - value).days if pd.notnull(value) else -1
        )
        df = df.drop(columns=["last_protection_at"])
    if "protections_applied_last_12m" not in df.columns:
        df["protections_applied_last_12m"] = 0

    missing_required = [col for col in BASE_REQUIRED_COLS if col not in df.columns]
    if missing_required:
        raise ValueError(f"Missing required feature columns: {missing_required}")

    default_zero_cols = list(ROLLING_OPTIONAL_COLS) + list(TELEMETRY_BASE_COLS) + list(TELEMETRY_RATIO_COLS)
    for window in TELEMETRY_WINDOWS:
        suffix = f"_{window}d"
        default_zero_cols.extend(f"{col}{suffix}" for col in TELEMETRY_BASE_COLS)
        default_zero_cols.extend(f"{col}{suffix}" for col in TELEMETRY_MEAN_COLS)
        default_zero_cols.extend(f"{col}{suffix}_max" for col in TELEMETRY_MAX_COLS)
    for column in default_zero_cols:
        if column not in df.columns:
            df[column] = 0.0
    df["fecha_dia"] = pd.to_datetime(df["fecha_dia"], errors="coerce")
    df = df.dropna(subset=["fecha_dia", "placa"])
    return df


def load_labels(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    for col in ["placa", "default_flag"]:
        if col not in df.columns:
            raise ValueError(f"Label file must contain column '{col}'")
    if "label_date" not in df.columns:
        df["label_date"] = pd.Timestamp.today().normalize()
    else:
        df["label_date"] = pd.to_datetime(df["label_date"], errors="coerce")
        df = df.dropna(subset=["label_date"])
    df["default_flag"] = df["default_flag"].astype(int)
    return df


def merge_datasets(features: pd.DataFrame, labels: pd.DataFrame, window_days: int) -> pd.DataFrame:
    # Sort features for efficient merge
    features_sorted = features.sort_values(["placa", "fecha_dia"])

    merged_rows = []
    for _, label_row in labels.iterrows():
        placa = label_row["placa"]
        cutoff = label_row["label_date"]
        subset = features_sorted[features_sorted["placa"] == placa]
        if cutoff is not pd.NaT:
            subset = subset[subset["fecha_dia"] <= cutoff]
        if window_days:
            subset = subset[subset["fecha_dia"] >= cutoff - pd.Timedelta(days=window_days)]
        if subset.empty:
            continue
        latest = subset.sort_values("fecha_dia").iloc[-1]
        merged = latest.to_dict()
        merged.update({
            "label_date": cutoff,
            "default_flag": label_row["default_flag"],
        })
        for extra_col in label_row.index:
            if extra_col not in {"placa", "default_flag", "label_date"}:
                merged[f"label_{extra_col}"] = label_row[extra_col]
        merged_rows.append(merged)

    if not merged_rows:
        raise ValueError("No matching rows found between features and labels")

    merged_df = pd.DataFrame(merged_rows)
    merged_df = merged_df.sort_values(["placa", "label_date"])
    return merged_df


def _safe_write(df: pd.DataFrame, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    suffix = path.suffix.lower()
    if suffix == ".parquet":
        try:
            df.to_parquet(path, index=False)
            return path
        except ImportError:
            path = path.with_suffix(".csv.gz")
            df.to_csv(path, index=False, compression="gzip")
            print(f"WARN: pyarrow not available, wrote CSV.GZ fallback instead -> {_rel(path)}")
            return path
    if suffix == ".gz":
        df.to_csv(path, index=False, compression="gzip")
        return path
    df.to_csv(path, index=False)
    return path


def main(argv: Iterable[str] | None = None) -> int:
    args = parse_args(argv)
    features_path = Path(args.features)
    labels_path = Path(args.labels)
    features = load_features(features_path)
    labels = load_labels(labels_path)
    merged = merge_datasets(features, labels, args.observation_window)
    written_path = _safe_write(merged, Path(args.output))
    print(f"Training dataset saved to {_rel(written_path)}")
    print(f"Rows: {len(merged)} | Columns: {len(merged.columns)}")

    write_metadata(
        written_path,
        script=__file__,
        inputs=[features_path, labels_path],
        extra={"rows": int(len(merged)), "columns": int(len(merged.columns))}
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
